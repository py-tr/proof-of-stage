"""Is the report text the evidence chain reads the same string the Zetaris layer serves?

python scripts/usl_text_equality.py   # no model call; writes docs/evidence/usl-text-equality.md

The chain (app/engine/run_case.py load_evidence) reads report text from the local corpus copy
(data/reports/path_reports.csv); the case page reads it from the USL table path_report. For a
frozen case list (the 25 review-queue cases of the deep-read bench, plus the 20 local-mode and 20
local-whole records), this compares the two strings exactly, and after normalising line endings.
"""

import asyncio
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.engine.local_mode import draw as local_mode_draw  # noqa: E402
from app.engine.local_whole import draw as local_whole_draw  # noqa: E402
from app.engine.reader_bench import frozen_case_ids  # noqa: E402
from app.engine.run_case import _rows  # noqa: E402
from app.reports.ingest import read_reports_csv  # noqa: E402
from app.usl.client import select  # noqa: E402
from app.usl.model import table_fqn  # noqa: E402
from app.usl.sqltext import sql_string  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "evidence" / "usl-text-equality.md"


async def main() -> None:
    cases = sorted(set(frozen_case_ids()) | set(local_mode_draw()) | set(local_whole_draw()))
    corpus = read_reports_csv()
    exact = normalised = differ = missing = 0
    diffs = []
    for cid in cases:
        rows = _rows(
            await select(
                f"SELECT report_text FROM {table_fqn('path_report')} WHERE case_id = {sql_string(cid)}",
                limit=5,
            )
        )
        local = corpus.get(cid)
        if not rows or local is None:
            missing += 1
            diffs.append((cid, "missing in USL" if not rows else "missing locally"))
            continue
        usl = str(rows[0].get("report_text") or "")
        loc = local.report_text
        if usl == loc:
            exact += 1
        elif usl.replace("\r\n", "\n").strip() == loc.replace("\r\n", "\n").strip():
            normalised += 1
        else:
            differ += 1
            diffs.append((cid, f"lengths {len(usl)} vs {len(loc)}"))
    result = {"cases": len(cases), "exact": exact, "same_after_line_endings": normalised, "differ": differ, "missing": missing}
    lines = [
        "# The chain's report text against the Zetaris layer's (no model call)",
        "",
        "Generated by `python scripts/usl_text_equality.py`. The evidence chain reads report text from the local corpus copy; the case page reads it from the USL table `path_report`. Frozen case list: the 25 review-queue cases plus the local-mode and local-whole records.",
        "",
        "| Measure | Result |",
        "|---|---|",
        f"| Cases compared | {len(cases)} |",
        f"| Identical strings | **{exact}** |",
        f"| Identical after normalising line endings | {normalised} |",
        f"| Different | {differ} |",
        f"| Missing on one side | {missing} |",
        "",
        *([f"- {c}: {why}" for c, why in diffs] or ["No differences."]),
    ]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(json.dumps(result))


if __name__ == "__main__":
    asyncio.run(main())
