"""Each Nemotron seat's quality, time and tokens, from committed logs only (no model call).

Writes docs/evidence/seat-cost-quality.md: (1) the deep read on the 25 review-queue reports, per
model (correct / wrong against the blind labels, median seconds and completion tokens per read,
from logs/reader-bench.jsonl and logs/label-scores.json); (2) the first read on the dial test's
28 consistent records (logs/lightning-r1-runs.jsonl, logs/r1-timing-runs.jsonl); (3) the chain
against always reading at the 4k budget, measured with Super at the first read (logs/dial-runs.jsonl)
and, labelled as an estimate, with Lightning at the first read as shipped.

    python scripts/seat_table.py
"""

import json
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOGS = ROOT / "logs"
OUT = ROOT / "docs" / "evidence" / "seat-cost-quality.md"
NAMES = {
    "lightning": "Lightning (30B, 3B active)",
    "super": "Super VL (120B, 12B active)",
    "ultra": "Ultra (550B, 55B active)",
}


def last(name: str) -> dict:
    rows = [x for x in (LOGS / name).read_text(encoding="utf-8").splitlines() if x.strip()]
    return json.loads(rows[-1])


def main() -> None:
    bench = [
        json.loads(x)
        for x in (LOGS / "reader-bench.jsonl").read_text(encoding="utf-8").splitlines()
        if x
    ]
    scores = json.loads((LOGS / "label-scores.json").read_text(encoding="utf-8"))["reader_bench"]
    lines = [
        "# Each Nemotron seat: quality, time and tokens (from committed logs, no new model call)",
        "",
        "Generated by `scripts/seat_table.py`. Every number below is read from a committed log of a pre-registered run; the one estimate is labelled.",
        "",
        "## Deep read: the 25 review-queue reports (the hard cases), scored against the blind labels",
        "",
        "| Model | Correct | Wrong | Median seconds per read | Median completion tokens per read | Thinking |",
        "|---|---|---|---|---|---|",
    ]
    for key in ("super", "ultra", "lightning"):
        mine = [r for r in bench if r["model_key"] == key and r.get("seconds") is not None]
        secs = statistics.median(r["seconds"] for r in mine)
        toks = statistics.median(r["tokens"] for r in mine if r.get("tokens") is not None)
        budget = "unbudgeted (Ultra rejects a budget)" if key == "ultra" else "4k budget"
        s = scores[key]
        lines.append(
            f"| {NAMES[key]} | {s['correct']} | {s['wrong']} | {secs:.1f} | {toks:,.0f} | {budget} |"
        )
    lines += [
        "",
        "Super keeps the deep read by the pre-registered rule (more correct and no more wrong): as many correct reads as Ultra with one fewer wrong. Ultra wrote far fewer completion tokens per read and was about as fast, so on tokens Ultra is the leaner reader here; per-token prices differ by model size and are not measured. Ultra's seat is the second reader that can only object. Lightning was slowest and least accurate on these hard reports.",
        "",
    ]
    lr, tm = last("lightning-r1-runs.jsonl"), last("r1-timing-runs.jsonl")
    d0 = last("dial-runs.jsonl")
    lines += [
        "## First read, thinking off: the dial test's 28 consistent records",
        "",
        "| Model | Records settled | Closings contradicted by the 4k read | Median seconds per read (controlled re-run) | Completion tokens, 28 records |",
        "|---|---|---|---|---|",
        f"| Lightning | {lr['lightning_settled']} of {lr['scored']} | {lr['lightning_vs_control']['disagree']} of {sum(lr['lightning_vs_control'].values())} | {tm['lightning']['median_seconds_per_read']} | {lr['lightning_tokens']:,} |",
        f"| Super VL | {lr['super_settled']} of {lr['scored']} | 0 of {d0['fields_closed_at_r1']} (dial test) | {tm['super']['median_seconds_per_read']} | {lr['super_r1_tokens']:,} |",
        "",
        "Lightning holds the first read for settling more records without a contradiction, not for cost: it is not faster and writes more tokens.",
        "",
    ]
    d = last("dial-runs.jsonl")
    r1_super = lr["super_r1_tokens"]
    deep_tokens = d["ladder_tokens"] - r1_super  # tokens the deep read spent in the measured chain
    open_records = d["scored"] - d["settled_at_r1"]
    per_open = deep_tokens / open_records
    shipped = lr["lightning_tokens"] + (lr["scored"] - lr["lightning_settled"]) * per_open
    always = d["control_tokens"]
    lines += [
        "## The chain against always reading at the 4k budget (same 28 records)",
        "",
        "| Setup | Completion tokens | vs always 4k | Status |",
        "|---|---|---|---|",
        f"| Always Super 4k | {always:,} | (baseline) | measured |",
        f"| First read Super off, then Super 4k on what stays open | {d['ladder_tokens']:,} | {d['ladder_tokens'] / always - 1:+.0%} | measured (dial test) |",
        f"| First read Lightning off, then Super 4k on what stays open (as shipped) | about {shipped:,.0f} | about {shipped / always - 1:+.0%} | **estimate, superseded by the measured −50% as shipped (`docs/evidence/shipped-cost-results.md`)**: Lightning's measured first-read tokens plus the measured deep-read tokens per open record ({per_open:,.0f}) times the {lr['scored'] - lr['lightning_settled']} records Lightning left open |",
        "",
    ]
    sc_path = LOGS / "shipped-cost-runs.jsonl"
    if sc_path.exists():
        sc = last("shipped-cost-runs.jsonl")
        v = sc["r1_vs_control"]
        lines += [
            "",
            "**Measured as shipped** (pre-registered, `docs/evidence/shipped-cost-results.md`, the dial test's 30 records, chain and always-4k control in the same session):",
            "",
            "| Setup | Completion tokens | vs always 4k | First-read closings vs the 4k read |",
            "|---|---|---|---|",
            f"| Always Super 4k (control) | {sc['control_tokens']:,} | (baseline) | |",
            f"| First read Lightning off, then Super 4k on what stays open | {sc['ladder_tokens']:,} | {sc['ladder_tokens'] / sc['control_tokens'] - 1:+.0%} | {v['agree']} agree, {v['disagree']} contradicted, {v['unconfirmed']} unconfirmed |",
            "",
        ]
    lines += [
        "Quality on these records: the chain's closed fields agreed with the always-4k read 30 times and contradicted it 0 times (dial test; Lightning: 33 agree, 0 contradicted, 5 unconfirmed). Different model sizes, each where it pays: the small model settles the easy records, the large one reads only what stays open.",
    ]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(OUT.read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
