"""Count every committed signed Nightshift receipt and check each one, offline.

python scripts/count_receipts.py   # no key, no network, no model; writes docs/evidence/receipt-count.md

Reads every envelope in docs/evidence/attest/*.jsonl (each run's kept envelopes), counts each
receipt id once, and checks its Ed25519 signature and that the signer is the committed pinned key.
"""

import glob
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.providers.receipts import _signed_receipt, key_fingerprint  # noqa: E402
from app.verify import pinned_fingerprint  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "evidence" / "receipt-count.md"


def count() -> dict:
    pin = pinned_fingerprint()
    seen: set[str] = set()
    files = {}
    for path in sorted(glob.glob(str(ROOT / "docs" / "evidence" / "attest" / "*.jsonl"))):
        n = verified = pinned = 0
        for line in Path(path).read_text(encoding="utf-8").splitlines():
            if not line.strip():
                continue
            row = json.loads(line)
            env = row.get("envelope") or row
            if not isinstance(env, dict) or "body" not in env:
                continue
            state, body, key = _signed_receipt(env)
            rid = (body or {}).get("receipt_id") or (
                (env.get("body") or {}).get("receipt") or {}
            ).get("receipt_id")
            if rid in seen:
                continue
            if rid:
                seen.add(rid)
            n += 1
            verified += state == "verified"
            pinned += state == "verified" and key_fingerprint(key) == pin
        files[Path(path).name] = {"receipts": n, "verified": verified, "pinned_key": pinned}
    total = {k: sum(f[k] for f in files.values()) for k in ("receipts", "verified", "pinned_key")}
    return {"pinned_fingerprint": pin, "files": files, "total": total}


if __name__ == "__main__":
    r = count()
    t = r["total"]
    rows = [
        f"| `{name}` | {f['receipts']} | {f['verified']} | {f['pinned_key']} |"
        for name, f in r["files"].items()
    ]
    OUT.write_text(
        "\n".join(
            [
                "# Every committed signed Nightshift receipt, checked offline",
                "",
                f"Generated by `python scripts/count_receipts.py` (no key, no network, no model). Pinned key fingerprint `{r['pinned_fingerprint']}`. Each receipt id is counted once.",
                "",
                f"**{t['receipts']} receipts; {t['verified']} have a valid Ed25519 signature; {t['pinned_key']} are signed by the pinned key.**",
                "",
                "| File | Receipts | Signature valid | Pinned key |",
                "|---|---|---|---|",
                *rows,
                "",
                "The shipped reader and case notes refuse any answer whose receipt is unsigned, signed by another key, served from cache, or names a model other than the one requested (`app/reader/reader.py`, `app/notes/note.py`, `app/providers/receipts.py`). What a signature does not show: the signed body covers the call (model, route, cache, prompt size), not the answer text; the key is self-pinned (Meterless publishes none).",
            ]
        )
        + "\n",
        encoding="utf-8",
    )
    print(json.dumps(t))
