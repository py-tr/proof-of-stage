"""Change every signed value of every committed attestation receipt, one at a time, and check each.

python scripts/tamper_bench.py   # offline: no key, no network, no model; writes docs/evidence/tamper-bench.md

For each envelope in docs/evidence/attest/envelopes.jsonl (the attestation census bundle), every
leaf value of the signed body (strings, numbers, booleans, nulls, at any depth) is changed once
(a string gets one character changed, a number +1, a boolean flipped, a null set to a string) and
the Ed25519 signature is checked again against the same signature. A forgery is caught when the
signature no longer verifies. A second pass replaces the signature with one made by a fresh key
over the changed body: the signature then verifies, and app.verify's pinned-key check catches it.
"""

import copy
import json
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.providers.receipts import _signed_receipt, canonical_body, key_fingerprint  # noqa: E402
from app.verify import pinned_fingerprint  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
BUNDLE = ROOT / "docs" / "evidence" / "attest" / "envelopes.jsonl"
OUT = ROOT / "docs" / "evidence" / "tamper-bench.md"


def leaves(node: Any, path: tuple = ()) -> list[tuple]:
    if isinstance(node, dict):
        return [p for k, v in node.items() for p in leaves(v, (*path, k))]
    if isinstance(node, list):
        return [p for i, v in enumerate(node) for p in leaves(v, (*path, i))]
    return [path]


def changed(value: Any) -> Any:
    if isinstance(value, bool):
        return not value
    if isinstance(value, (int, float)):
        return value + 1
    if isinstance(value, str):
        return (value[:-1] + ("b" if value[-1:] == "a" else "a")) if value else "a"
    return "x"


def set_at(node: Any, path: tuple, value: Any) -> None:
    for key in path[:-1]:
        node = node[key]
    node[path[-1]] = value


def get_at(node: Any, path: tuple) -> Any:
    for key in path:
        node = node[key]
    return node


def run() -> dict[str, Any]:
    import base64

    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

    rows = [json.loads(x) for x in BUNDLE.read_text(encoding="utf-8").splitlines() if x.strip()]
    pinned = pinned_fingerprint()
    forger = Ed25519PrivateKey.generate()
    forger_pub = base64.b64encode(forger.public_key().public_bytes_raw()).decode()
    total = caught = originals_ok = resigned_verify = resigned_caught = 0
    for row in rows:
        env = row["envelope"]
        originals_ok += _signed_receipt(env)[0] == "verified"
        for path in leaves(env["body"]):
            forged = copy.deepcopy(env)
            set_at(forged["body"], path, changed(get_at(env["body"], path)))
            total += 1
            caught += _signed_receipt(forged)[0] != "verified"
        # a careful forger re-signs one changed body with their own key
        forged = copy.deepcopy(env)
        first = leaves(forged["body"])[0]
        set_at(forged["body"], first, changed(get_at(env["body"], first)))
        forged["pubkey_b64"] = forger_pub
        forged["sig_b64"] = base64.b64encode(forger.sign(canonical_body(forged["body"]))).decode()
        state, _, key = _signed_receipt(forged)
        resigned_verify += state == "verified"
        resigned_caught += key_fingerprint(key) != pinned
    return {
        "receipts": len(rows),
        "originals_verified": originals_ok,
        "forgeries": total,
        "caught": caught,
        "resigned": len(rows),
        "resigned_signature_verifies": resigned_verify,
        "resigned_caught_by_pinned_key": resigned_caught,
    }


if __name__ == "__main__":
    r = run()
    OUT.write_text(
        "\n".join(
            [
                "# Tamper bench: every signed value of every attestation receipt, changed one at a time",
                "",
                "Generated by `python scripts/tamper_bench.py` (offline: no key, no network, no model). A test, not a pre-registered measurement: the result is determined by the signature scheme.",
                "",
                "| Measure | Result |",
                "|---|---|",
                f"| Receipts in the attestation bundle | {r['receipts']} ({r['originals_verified']} verify as committed) |",
                f"| Forgeries: one signed value changed (every leaf of every body) | **{r['caught']} of {r['forgeries']} caught** (signature no longer verifies) |",
                f"| A forger re-signs a changed body with their own key | the signature verifies on {r['resigned_signature_verifies']} of {r['resigned']}; **{r['resigned_caught_by_pinned_key']} of {r['resigned']} caught** by the pinned-key check (`python -m app.verify`) |",
                "",
                "What it does not show: the signed body covers the call (model, route, cache, prompt size), not the answer text, so a pass proves which model was called and that the record was not changed, not that the answer is right; and the pinned key is self-pinned (Meterless publishes none).",
            ]
        )
        + "\n",
        encoding="utf-8",
    )
    print(json.dumps(r, indent=2))
